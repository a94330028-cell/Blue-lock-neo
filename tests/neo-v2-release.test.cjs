'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const updates=require('../web/neo-updates-v1060.js');
const text=p=>fs.readFileSync(p,'utf8');
const info=JSON.parse(text('CHANGELOG.json'));
assert.equal(text('web/VERSION').trim(),'2.0.0');
assert.ok(text('web/UPDATE_BUILD').trim().localeCompare('10.6.22',undefined,{numeric:true})>=0,'build cannot roll back');
assert.ok(updates.validate(info));
assert.equal(info.current_version,'2.0.0');
assert.deepEqual(info.releases.slice(0,2).map(r=>r.version),['2.0.0','1.8.0']);
const categories=['novidades','correcoes','jogabilidade','visual','otimizacoes','importantes'];
const notes=categories.flatMap(k=>info.releases[0][k]||[]);
assert.ok(notes.length>0&&notes.length<=8,'patch from the current version only');
assert.ok(notes.reduce((sum,s)=>sum+s.length,0)<=1400,'keep one release short');
assert.ok(updates.formatRelease(info).includes('v2.0.0'));
assert.ok(!updates.formatRelease(info).includes('Conteúdo 10.6.13'),'1.x details stay archived');
const js=text('web/neo-updates-v1060.js');
const css=text('web/neo-updates-v1060.css');
assert.ok(js.includes('neo1060-archive')&&js.includes("data.releases.slice(1)"),'prior releases stay behind lazy archive');
assert.ok(css.includes('neo1060-archive-toggle'),'legacy history is accessible');
const app=text('app/src/main/java/com/neoegoist/simulator/MainActivity.java');
assert.ok(app.includes('BUNDLED_WEB_VERSION = "'+fs.readFileSync('web/UPDATE_BUILD','utf8').trim()+'"'));
assert.ok(app.includes('appassets.androidplatform.net'),'WebView origin preserving saves must not change');
assert.ok(app.includes('installed_web_version'),'Android updater continues to remember installed content');
const gradle=text('app/build.gradle');
assert.ok(gradle.includes('versionCode 119')&&gradle.includes("versionName '2.0.0'"));
assert.ok(!js.includes('localStorage.clear('),'must never erase saves to migrate patch versions');
console.log('PASS NEO 2.0 foundation: new patch, archived history, compatibility and Android build numbers');
