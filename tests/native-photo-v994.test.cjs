'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const java=read('app/src/main/java/com/neoegoist/simulator/MainActivity.java');
const app=read('web/app.js');
const studio=read('web/neo-studio-v970.js');
const worker=read('web/service-worker.js');
const gradle=read('app/build.gradle');
assert.ok(java.includes('REQUEST_NATIVE_PORTRAIT = 1503'), 'native photo chooser has own request code');
assert.ok(java.includes('new Intent(Intent.ACTION_OPEN_DOCUMENT)'), 'standard Android document/photo picker');
assert.ok(java.includes('getContentResolver().openInputStream(uri)'), 'Android, not JS FileReader, opens content URI');
assert.ok(java.includes('BitmapFactory.decodeStream(input, null, opts)'), 'bounded native decode');
assert.ok(java.includes('opts.inSampleSize = sample'), 'large photos downsampled');
assert.ok(java.includes('square.compress(Bitmap.CompressFormat.JPEG, 84, bytes)'), 'portrait converted to compact JPEG');
assert.ok(java.includes('getContentResolver()'), 'photo stays on device');
assert.ok(java.includes('@JavascriptInterface public void pickPortrait(String name)'), 'Android native picker exposed');
assert.ok(java.includes("new CustomEvent('neo:native-portrait'"), 'native image delivered to app');
assert.ok(java.includes('requestCode == REQUEST_NATIVE_PORTRAIT'), 'native result routed correctly');
assert.ok(app.includes('window.BlueLockAndroid?.pickPortrait'), 'portrait gallery uses native picker');
assert.ok(app.includes("window.addEventListener('neo:native-portrait'"), 'app receives native image');
assert.ok(app.includes("savePortraitImage('custom',name,data)"), 'native image saves to existing private indexedDB');
assert.ok(studio.includes('window.BlueLockAndroid?.pickPortrait'), 'historical clubs use native picker too');
assert.ok(worker.includes('blue-lock-neo-v1.9.2-ego12'));
assert.equal(read('web/VERSION').trim(),'1.8.0');
assert.ok(gradle.includes('versionCode 116')&&gradle.includes("versionName '1.8.0'"));
console.log('PASS v9.9.4: native Android photo picker, downsample/encode, both galleries, preserves IndexedDB and versions');
