'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../web');
const E=require(path.join(root,'engine.js'));
const H=require(path.join(root,'neo-historic-teams-v970.js'));
const C=require(path.join(root,'neo-coach-v980.js'));
global.NeoCoach980=C;
H.install(E);
assert.equal(E.TEAMS.length,5,'Original league is unchanged');
assert.equal(E.allTeams().length,9,'Four historical clubs remain');
assert.ok(C.compatible('LD','LD') && !C.compatible('LD','LE'));
assert.ok(!C.compatible('GOL','CA'));
const bm=E.teamById('bm'),original=bm.players.slice(),bench=bm.reserves.slice();
const bad={schema:2,rounds:[{round:1,games:[{home:'bm',away:'px',result:[0,2]}]},{round:2,games:[{home:'bm',away:'ba',result:[0,3]}]}],career:{players:{}}};
for(const name of ['Mensah','Birkenstock','Ranze Kurona'])bad.career.players[name+'|bm']={games:2,ratingSum:10};
const plan=C.planLineup(bm,bad,E.Attr);
assert.equal(plan.form.streak,2);
assert.ok(plan.changes.length>=1,'Coach must rotate poor starting line-up');
assert.ok(plan.changes.every(x=>x.position>0&&C.compatible(x.role,C.reserveRole(bm,x.in))));
assert.equal(new Set(plan.players).size,11,'Coach must not repeat a player');
assert.equal(plan.players[0],original[0],'Goalkeeper must stay in goal');
assert.deepEqual(C.planLineup(bm,{rounds:[],career:{players:{}}},E.Attr).players,original);
const match=new E.Match('bm','px',149,null,bad);
assert.ok(match.coachPlans[0].changes.length,'Pre-match plan used by actual game engine');
assert.deepEqual(bm.players,original,'No permanent changes to original club squad');
assert.deepEqual(bm.reserves,bench,'No permanent changes to original bench');
assert.ok(match.startingLineups[0].every((x,i)=>x.role===match.teams[0].formation[i].role),
 'o XI deve usar as posições da formação escolhida pelo técnico, sem alterar o elenco registrado');
match.time=55*60;match.phase='play';match.score=[0,2];match.lastCoachCheck=-999;match.ball.owner=null;
match._coachDecisions();
assert.equal(match.tactics[0],'attack','Losing coach changes to attack early');
assert.equal(match.pressing[0],'high','Losing coach increases pressure');
assert.ok(match.coachDecisions.find(x=>x.side===0&&x.type==='tactic'));
assert.ok(match.pendingSubs[0]?.length>0,'Losing coach plans substitutions before minute 58');
match._applyPendingSubs();
assert.ok(match.subRecords.some(x=>x.side===0),'The proposed substitutions are actually applied');
const result=match.result();
assert.ok(result.startingLineups.length===2&&result.coachDecisions.length>0);
assert.ok(result.coachPlans[0].form.streak===2);
const cup={rounds:[{round:1,games:[{home:'mu08',away:'fla19',result:[0,3]}]},{round:2,games:[{home:'mu08',away:'mir25',result:[1,2]}]}],career:{players:{}}};
const h=E.teamById('mu08');const change=C.planLineup(h,cup,E.Attr);
assert.ok(change.form.underPressure);assert.ok(change.changes.every(x=>C.compatible(x.role,C.reserveRole(h,x.in))));
for(const t of E.allTeams()){assert.equal(t.players.length,11);assert.equal((t.formation||E.DEFAULT_FORMATION).length,11);assert.equal((t.formation||E.DEFAULT_FORMATION)[0].role,'GOL');}
const js=fs.readFileSync(path.join(root,'neo-squads-v980.js'),'utf8');
const css=fs.readFileSync(path.join(root,'neo-squads-v980.css'),'utf8');
for(const kw of ['neo980-pitch','neo980-select','neo980-coach-card','neo980-ovr','data-neo960-profile','NeoPortraitUI','E.allTeams','neo980-bench'])assert.ok(js.includes(kw),kw);
for(const kw of ['.neo980-pitch','.neo980-player','.neo980-headshot','.neo980-ovr','.neo980-coach-changes'])assert.ok(css.includes(kw),kw);
assert.equal(fs.readFileSync(path.join(root,'VERSION'),'utf8').trim(),'2.0.0');
console.log('PASS v9.8: coaching driven by losing streaks, early subs, preserved XI positions, OVR pitch and 9 club rosters');
