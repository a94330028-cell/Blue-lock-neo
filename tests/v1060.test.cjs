'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const U=require('../web/neo-updates-v1060.js');
const read=p=>fs.readFileSync(p,'utf8');
const data=JSON.parse(read('CHANGELOG.json'));
assert.equal(U.validate(data),true);
assert.equal(U.compare('1.0.0','0.9.9'),1);
assert.equal(U.compare('1.0.0','1.0.0'),0);
assert.equal(U.compare('0.9.9','1.0.0'),-1);
assert.equal(U.validate({...data,current_version:'10.7.0'}),false);
assert.equal(data.current_version,read('web/VERSION').trim());
assert.equal(data.project,'Blue Lock NEO');
assert.equal(data.releases[0].version,'1.0.0');
assert.equal(data.releases.length,1,'only the first public launch appears in history');
assert.ok(U.formatRelease(data).includes('v1.0.0'),'release notes are copyable');
assert.ok(U.SEEN_KEY.includes('official-v1'),'unread key resets after old beta numbering');
assert.equal(read('web/UPDATE_BUILD').trim(),'10.6.1','Android delivery build remains monotonic');
assert.ok(data.releases.every(r=>r.novidades.length+r.correcoes.length+r.jogabilidade.length+r.visual.length+r.otimizacoes.length+r.importantes.length>0));
const page=read('web/index.html'),style=read('web/neo-updates-v1060.css'),script=read('web/neo-updates-v1060.js');
assert.ok(page.includes('neo-updates-v1060.js'), 'real page loads history script');
assert.ok(page.includes('neo-updates-v1060.css'), 'real page loads history styles');
assert.ok(fs.existsSync('web/CHANGELOG.json'), 'changelog mirrored into site build');
assert.deepEqual(JSON.parse(read('web/CHANGELOG.json')),data,'site and bot share identical changelog');
assert.ok(script.includes("SEEN_KEY='neo-updates-last-seen-official-v1'"),'stable 1.0 unread state is separate from player saves');
assert.ok(script.includes("doc.getElementById('more')"),'updates accessible from More on mobile');
assert.ok(script.includes("fetch(SOURCE,{cache:'no-store'})"),'updates read actual version history');
assert.ok(script.includes('preview.onerror'), 'missing image gracefully hidden');
assert.ok(script.includes('neo1060-copy'),'first launch includes sharing its release notes');
assert.ok(U.formatRelease(data).includes('v1.0.0'),'copy includes the public launch number');
assert.ok(style.includes('@media(max-width:420px)'),'mobile layout included');
assert.ok(!script.includes("localStorage.clear("),'user saves never deleted');
const worker=read('web/service-worker.js');
for(const f of ['./CHANGELOG.json','./neo-updates-v1060.js','./neo-updates-v1060.css'])assert.ok(worker.includes(f),'cached offline '+f);
assert.ok(worker.includes('blue-lock-neo-v1.0.0-public-launch'));
const wf=read('.github/workflows/publicar-site.yml');
assert.ok(wf.includes("if: steps.deployment.outcome == 'success' && steps.neo_media.outcome == 'success'"));
assert.ok(wf.includes('DISCORD_WEBHOOK_URL: $'+'{{ secrets.DISCORD_WEBHOOK_URL }}'));
assert.ok(wf.includes('tools/neo_update_announcement.py publish'));
assert.ok(!wf.includes('DISCORD_WEBHOOK_URL: https://'),'no leaked Discord webhook token');
const manual=read('.github/workflows/neo-discord-updates.yml');
assert.ok(manual.includes('workflow_dispatch:'));
assert.ok(!/^\s+push:/.test(manual),'manual test does not send on commits');
assert.ok(manual.includes('neo-update-preview.json'));
assert.ok(manual.includes('retry_pending'));
const validator=read('tools/neo_update_announcement.py');
assert.ok(validator.includes('verify_live_version(version)'));
assert.ok(validator.includes('neo-updates/'));
assert.ok(validator.includes('{"parse": []}'));
const native=read('app/src/main/java/com/neoegoist/simulator/MainActivity.java'),gradle=read('app/build.gradle');
assert.ok(native.includes('BUNDLED_WEB_VERSION = "10.6.1"'));
assert.ok(gradle.includes("versionName '1.0.0'"));
assert.ok(gradle.includes('versionCode 108'));
console.log('PASS NEO 10.6: secure post-deploy announce, no-spam manual preview, truthful changelog and mobile archive');
