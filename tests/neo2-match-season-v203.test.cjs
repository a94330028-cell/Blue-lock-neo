'use strict';
/* End-to-end simulation after all official v2.0 and legacy AI hooks are installed. */
const assert=require('node:assert/strict');
const E=require('../web/engine.js');
const Deep=require('../web/neo2-deep-ai-v202.js');
const Old=require('../web/neo-ai-v110.js');
const Evolution=require('../web/neo-evolution-v120.js');
const Advanced=require('../web/neo-advanced-v200.js');
const Universe=require('../web/neo-universe-v220.js');
const Twelve=require('../web/neo-twelve-v230.js');
const Pulse=require('../web/neo-match-pulse-v240.js');
assert.equal(Deep.adapt(E),true,'deep AI installs before legacy module wrappers');
Old.adapt(E);Evolution.adapt(E);Advanced.adapt(E);Universe.adapt(E);
Twelve.adapt(E);Pulse.adapt(E);
assert.equal(Deep.adapt(E),false,'deep AI hooks cannot duplicate');
const season=E.createSchedule(4);E.Progression.ensure(season);
const fixtures=season.rounds.flatMap(r=>r.games).slice(0,16);
let totalGoals=0,deepDecisions=0,adapts=0,penalties=0,penaltyGoals=0,duels=0;
for(let i=0;i<fixtures.length;i++){
 const fixture=fixtures[i];
 const match=new E.Match(fixture.home,fixture.away,2026000+i*317,season.career,season);
 match.rollGameplan();
 const r=match.runToEnd();
 assert.ok(match.finished,'game actually ended');
 assert.deepEqual(match.score,r.score);
 assert.ok(r.score.every(v=>Number.isInteger(v)&&v>=0&&v<28),'scores remain valid');
 assert.ok(match.players.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)&&p.stamina>=0&&p.stamina<=100));
 assert.equal(r.neo2DeepAI?.schema,2);
 assert.equal(r.neo2DeepAI.deepDecisions.length,2);
 assert.ok(r.neo2DeepAI.observedPasses<=80,'bounded memory in long matches');
 assert.ok(r.neo2DeepAI.adaptations.length<=18,'coaching history bounded');
 assert.ok(r.stats.penaltiesScored.every((v,s)=>v<=r.stats.penalties[s]));
 assert.ok(r.shots.every(x=>Number.isFinite(x.x)&&Number.isFinite(x.y)));
 assert.ok(r.goalRecords.length===r.score[0]+r.score[1],'no invented scoreboard goals');
 assert.ok(r.coachDecisions.every(c=>c.minute>=0&&c.minute<=100),'coach only reacts inside the game');
 totalGoals+=r.score[0]+r.score[1];
 deepDecisions+=r.neo2DeepAI.deepDecisions.reduce((a,b)=>a+b,0);
 adapts+=r.neo2DeepAI.adaptations.length;
 duels+=r.neo2DeepAI.observedDuels;
 penalties+=r.stats.penalties.reduce((a,b)=>a+b,0);
 penaltyGoals+=r.stats.penaltiesScored.reduce((a,b)=>a+b,0);
 // Results and player statistics must stay compatible with the season save.
 assert.equal(E.recordFixture(season,fixture,match),true,'save genuine match details');
}
assert.ok(totalGoals>=3,'season contains goals generated by real engine: '+totalGoals);
assert.ok(duels>=10,'learning observes genuine physical duels: '+duels);
assert.ok(deepDecisions>=3,'brain must alter genuine on-ball decisions: '+deepDecisions);
assert.ok(penaltyGoals<=penalties);
assert.ok(fixtures.every(f=>Array.isArray(f.result)&&f.result.length===2));
const a=new E.Match('bm','px',80321,season.career,season);
const b=new E.Match('bm','px',80321,season.career,season);
a.rollGameplan();b.rollGameplan();
for(let i=0;i<1100;i++){a.step(E.TICK);b.step(E.TICK);}
assert.deepEqual(a.score,b.score,'identical seed and tactics reproduce score');
assert.deepEqual(a.result().neo2DeepAI,b.result().neo2DeepAI,'reproducible tactical memory');
console.log('PASS NEO 2.0 live league: '+JSON.stringify({games:fixtures.length,goals:totalGoals,deepDecisions,adaptations:adapts,duels,penalties,penaltyGoals}));
